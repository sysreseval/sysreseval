class TestRuby:
    def test_strip_comments(self):
        text = ('require "yaml"  # the parser\n'
                '# machines: alpha 192.168.1.2\n'
                'x = "a # not a comment"\n'
                "y = 'b # nor this' # but this\n"
                'z = "esc \\" # still a string"\n'
                '=begin\nalpha\n=end\n'
                'end\n')
        stripped = vh.strip_ruby_comments(text)
        assert stripped.splitlines() == ['require "yaml"', '', 'x = "a # not a comment"', "y = 'b # nor this'",
                                         'z = "esc \\" # still a string"', 'end']
        assert 'alpha' not in stripped


class TestTimes:
    def test_parse_timestamp(self):
        ts = vh.parse_timestamp("2026-11-24T13:37:28.51471456Z")
        assert ts.microsecond == 514714 and ts.utcoffset().total_seconds() == 0
        assert vh.parse_timestamp("2026-11-24T13:37:28+02:00").utcoffset().total_seconds() == 7200
        assert vh.parse_timestamp("0001-01-01T00:00:00Z") is None and vh.parse_timestamp("") is None
        assert vh.parse_timestamp("garbage") is None
        assert vh.unix_time("1970-01-01T00:00:10Z") == 10.0 and vh.unix_time("") is None

    def test_started_after_creation(self):
        containers = vh.parse_docker_containers(CONTAINERS)
        assert vh.started_after_creation(containers["w3b"])           # 17 s later: restarted
        assert not vh.started_after_creation(containers["c775"])      # 0.28 s: the first start
        assert not vh.started_after_creation(containers["dead"])      # never started
        assert vh.started_after_creation(containers["c775"], min_gap=0.1)


