class TestStateSide:
    def test_daemon_json(self):
        """The configuration the lab writes before dockerd starts (the devops13 image has none):
        docker0 and the pool of the networks outside the lab's addresses, small logs."""
        assert vh.DAEMON_JSON_PATH == "/etc/docker/daemon.json"
        assert vh.DAEMON_JSON.endswith("\n")
        assert json.loads(vh.DAEMON_JSON) == {
            "bip": "10.250.0.1/24",
            "default-address-pools": [{"base": "10.251.0.0/16", "size": 24}],
            "log-driver": "json-file",
            "log-opts": {"max-size": "1m", "max-file": "2"},
        }

    def test_start_docker(self):
        cmd = vh.start_docker_cmd(45)
        assert cmd.startswith("systemctl start docker && ") and "timeout 45" in cmd and "docker info" in cmd

    def test_import_rootfs(self):
        cmd = vh.import_rootfs_cmd("/usr/share/sre-vagrant/debian13-rootfs.tar.zst", "sre/debian13:1.2.3")
        assert cmd.startswith("docker image inspect sre/debian13:1.2.3 >/dev/null 2>&1 || zstd -dc ")
        assert "--change 'CMD [\"/bin/sh\",\"-c\",\"ssh-keygen -A >/dev/null && exec /usr/sbin/sshd -D -e\"]'" in cmd
        assert cmd.endswith("- sre/debian13:1.2.3 >/dev/null")

    def test_import_rootfs_runs_in_sh(self, tmp_path):
        """The command is valid sh (dash), the quoting of the CMD survives."""
        cmd = vh.import_rootfs_cmd("/x.tar.zst", "a/b:1")
        fake = tmp_path / "bin"
        fake.mkdir()
        (fake / "docker").write_text("#!/bin/sh\n[ \"$1\" = image ] && exit 1\nprintf '%s\\n' \"$@\" > \"$OUT\"\n")
        (fake / "zstd").write_text("#!/bin/sh\nexit 0\n")
        for f in fake.iterdir():
            f.chmod(0o755)
        out = tmp_path / "args"
        subprocess.run(["sh", "-c", cmd], check=True, env={"PATH": f"{fake}:/usr/bin:/bin", "OUT": str(out)})
        args = out.read_text().splitlines()
        assert args[:3] == ["import", "--change", 'CMD ["/bin/sh","-c","ssh-keygen -A >/dev/null && exec /usr/sbin/sshd -D -e"]']
        assert args[-2:] == ["-", "a/b:1"]

    def test_docker_box_files(self):
        metadata, vagrantfile = vh.docker_box_files("sre/debian13:2.5.4", extra='d.env = { "BOX_RELEASE" => "1.0.0" }')
