class TestMachines:
    def test_parse(self):
        machines = vh.parse_vagrant_machines(LISTING)
        assert set(machines) == {('/root/vagrant/cluster', 'app1'), ('/root/vagrant/boxes/app', 'default'),
                                 ('/root/vagrant/hello', 'default'), ('/root/vagrant/sync', 'default')}
        app1 = machines[('/root/vagrant/cluster', 'app1')]
        assert app1.id.startswith('313d55') and app1.private_key and app1.box['version'] == '2.5.4'
        hello = machines[('/root/vagrant/hello', 'default')]
        assert not hello.private_key and hello.box == {}
        assert machines[('/root/vagrant/sync', 'default')].box == {}        # bad JSON
        assert machines[('/root/vagrant/boxes/app', 'default')].box['name'] == 'colibri/base'
        assert vh.parse_vagrant_machines('') == {} and vh.parse_vagrant_machines(None) == {}

    def test_listing_command_in_sh(self, tmp_path):
        """The listing command run by sh over a fake project tree."""
        root = tmp_path / "vagrant"
        d1 = root / "web" / ".vagrant" / "machines" / "web" / "docker"
        d2 = root / "boxes" / "app" / ".vagrant" / "machines" / "default" / "docker"
        d3 = root / "hello" / ".vagrant" / "machines" / "default" / "docker"   # destroyed: empty dir
        for d in (d1, d2, d3):
            d.mkdir(parents=True)
        (d1 / "id").write_text("1234")
        (d1 / "private_key").write_text("KEY")
        (d1 / "box_meta").write_text(BOX)
        (d2 / "id").write_text("5678")
        cmd = vh.vagrant_machines_cmd((f"{root}/*", f"{root}/*/*"))
        out = subprocess.run(["sh", "-c", cmd], check=True, capture_output=True, text=True).stdout
        machines = vh.parse_vagrant_machines(out)
        assert set(machines) == {(f"{root}/web", "web"), (f"{root}/boxes/app", "default")}
        web = machines[(f"{root}/web", "web")]
        assert web.id == "1234" and web.private_key and web.box["name"] == "sre/debian13"
        assert not machines[(f"{root}/boxes/app", "default")].private_key


class TestContainers:
    def test_parse(self):
        containers = vh.parse_docker_containers("noise\n" + CONTAINERS + "\n")
        assert set(containers) == {"c775", "w3b", "dead"}
        charlie = containers["c775"]
        assert charlie.running and charlie.hostname == "charlie" and charlie.name == "fleet_charlie_1795529060"
        assert charlie.ips() == {"bridge": "10.250.0.15", "vagrant_network_192.168.213.0/24": "192.168.213.142"}
        assert charlie.mount_at("/vagrant") == {"type": "bind", "source": "/root/vagrant/fleet",
                                                "destination": "/vagrant"}
        assert charlie.mount_at("/srv/app") is None and charlie.published() == {}
        web = containers["w3b"]
        assert web.env == {"APP_MODE": "staging", "EMPTY": ""}
        assert web.host_ports(80) == [8080] and web.host_ports(22) == [2200] and web.host_ports(443) == []
        assert web.published() == {80: [8080]}                  # 22 left out, udp ignored
        dead = containers["dead"]
        assert not dead.running and dead.env == {} and dead.mounts == [] and dead.ports == {} and dead.networks == {}

    def test_parse_garbage(self):
        assert vh.parse_docker_containers("") == {} and vh.parse_docker_containers("[not json") == {}
        assert vh.parse_docker_containers('[{"name": "no id"}, 3]') == {}

    def test_commands_use_jq(self):
        assert vh.docker_containers_cmd().startswith("docker ps -aq | xargs -r docker inspect | jq -c ")
        assert vh.docker_networks_cmd().startswith("docker network ls -q | xargs -r docker network inspect | jq -c ")

    @pytest.mark.skipif(subprocess.run(["sh", "-c", "command -v jq"], capture_output=True).returncode != 0,
                        reason="jq not installed")
    def test_jq_filter_on_an_inspect_document(self):
        """The jq programs on a docker inspect document (the shape of Docker 26)."""
        doc = [{"Id": "abc", "Name": "/web_web_1", "Created": "2026-11-24T13:37:11Z",
                "State": {"Status": "running", "Running": True, "StartedAt": "2026-11-24T13:37:28Z"},
                "Config": {"Hostname": "web", "Image": "sre/debian13:2.5.4", "Env": ["A=1"]},
                "Mounts": [{"Type": "bind", "Source": "/s", "Destination": "/d", "Mode": "", "RW": True}],
                "HostConfig": {"PortBindings": {"80/tcp": [{"HostIp": "", "HostPort": "8080"}]}},
                "NetworkSettings": {"Networks": {"bridge": {"IPAddress": "10.250.0.3", "IPPrefixLen": 24,
                                                            "MacAddress": "02:42:0a:fa:00:03", "Gateway": "x"}}}}]
        program = vh._JQ_CONTAINERS
        out = subprocess.run(["jq", "-c", program], input=json.dumps(doc), capture_output=True, text=True,
                             check=True).stdout
        c = vh.parse_docker_containers(out)["abc"]
        assert c.name == "web_web_1" and c.running and c.env == {"A": "1"} and c.host_ports(80) == [8080]
        assert c.networks == {"bridge": {"ip": "10.250.0.3", "prefix": 24, "mac": "02:42:0a:fa:00:03"}}
        nets = [{"Name": "host", "Driver": "host", "IPAM": {"Config": None}, "Options": None},
                {"Name": "pub", "Driver": "macvlan", "IPAM": {"Config": [{"Subnet": "10.0.0.0/24"}]},
                 "Options": {"parent": "eth0"}}]
        out = subprocess.run(["jq", "-c", vh._JQ_NETWORKS], input=json.dumps(nets), capture_output=True, text=True,
                             check=True).stdout
        parsed = vh.parse_docker_networks(out)
        assert parsed["host"].subnets == [] and parsed["pub"].parent == "eth0"


